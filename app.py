def classify(text):
    """Run the fine-tuned model. Returns (category, model_tokens, seconds)."""
    enc = tokenizer(
        PROMPT.format(ticket=text),
        return_tensors="pt",
        truncation=True,
        max_length=MAX_LEN,
    )
    n_tokens = int(enc.input_ids.shape[1])

    start = time.perf_counter()
    with torch.no_grad():
        out = model.generate(**enc, max_new_tokens=8)
    seconds = time.perf_counter() - start

    raw = tokenizer.decode(out[0], skip_special_tokens=True).strip()
    category_lookup = {label.lower(): label for label in LABELS}
    return category_lookup.get(raw.lower(), "Unknown"), n_tokens, seconds


URGENT_PHRASES = [
    "urgent", "immediately", "asap", "emergency", "hacked", "stolen",
    "unauthorized", "unauthorised", "fraud", "locked out", "charged twice",
    "double charged", "not working at all",
]


def get_priority(text):
    """Simple keyword rule (NOT the model): High if the ticket contains an urgent phrase."""
    lowered = text.lower()
    return "High" if any(phrase in lowered for phrase in URGENT_PHRASES) else "Normal"


def label_probs(text):
    """Estimate relative likelihoods for the four candidate category labels."""
    try:
        enc = tokenizer(
            [PROMPT.format(ticket=text)] * len(LABELS),
            return_tensors="pt",
            truncation=True,
            max_length=MAX_LEN,
        )
        labels = tokenizer(LABELS, padding=True, return_tensors="pt").input_ids
        mask = labels != tokenizer.pad_token_id
        labels_for_loss = labels.clone()
        labels_for_loss[~mask] = -100

        with torch.no_grad():
            logits = model(**enc, labels=labels_for_loss).logits

        log_probs = torch.log_softmax(logits, dim=-1).gather(
            -1, labels.unsqueeze(-1)
        ).squeeze(-1)
        sequence_log_probs = (log_probs * mask).sum(dim=1)
        probabilities = torch.softmax(sequence_log_probs, dim=0).tolist()
        return dict(zip(LABELS, probabilities))
    except Exception:
        return None


def log_ticket(source, text, category, probs, priority):
    confidence = None if (probs is None or category not in probs) else round(probs[category], 3)
    st.session_state.setdefault("log", []).append(
        {
            "time": time.strftime("%H:%M:%S"),
            "source": source,
            "ticket": text,
            "category": category,
            "confidence": confidence,
            "priority": priority,
        }
    )


def chat_reply(message):
    """Returns (reply_text, metadata). Only the category comes from the model."""
    lowered = message.lower()
    words = re.findall(r"[a-z0-9']+", lowered)

    if len(words) <= 4:
        for keys, answer in SMALL_TALK:
            if any(word in keys for word in words):
                return answer, {"source": "Small-talk rule (model not used)"}

    category, n_tokens, seconds = classify(message)
    probabilities = label_probs(message)
    priority = get_priority(message)
    log_ticket("chat", message, category, probabilities, priority)

    best_answer, best_score = None, 0
    for keywords, answer in FAQ.get(category, []):
        score = sum(keyword in lowered for keyword in keywords)
        if score > best_score:
            best_answer, best_score = answer, score

    if best_answer:
        reply, source = best_answer, "FAQ answer"
    else:
        reply = f"{REPLIES[category]} {FOLLOW_UP[category]}"
        source = "Category template"

    confidence = probabilities[category] if probabilities and category in probabilities else None
    return reply, {
        "category": category,
        "conf": confidence,
        "priority": priority,
        "tokens": n_tokens,
        "ms": seconds * 1000,
        "source": source,
    }


