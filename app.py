def chips_html(meta):
    if "category" not in meta:
        return (
            f'<div class="chips"><span class="chip">'
            f'{html.escape(meta["source"])}</span></div>'
        )

    items = [f'Model: {meta["category"]}']
    if meta["conf"] is not None:
        items.append(f'{meta["conf"] * 100:.0f}% confidence')
    items.extend(
        [
            f'{meta["priority"]} priority (rule)',
            f'{meta["tokens"]} tokens',
            f'{meta["ms"]:.0f} ms',
            f'Reply: {meta["source"]}',
        ]
    )
    return (
        '<div class="chips">'
        + "".join(
            f'<span class="chip">{html.escape(item)}</span>' for item in items
        )
        + "</div>"
    )


def result_html(result):
    category = result["category"]
    probabilities = result["probs"]
    color = CAT_COLORS.get(category, "#64748B")
    confidence = probabilities.get(category) if probabilities else None

    output = [
        '<div class="fl">Predicted category (fine-tuned model)</div>',
        f'<div class="cat"><span class="dot" style="background:{color}"></span>'
        f'{html.escape(category)}</div>',
    ]

    if confidence is not None:
        output.append(
            f'<div class="sub">Confidence {confidence * 100:.1f}% '
            f'across the four categories</div>'
        )
        if confidence < 0.5:
            output.append(
                '<div class="warn">Low confidence. A person should check this ticket.</div>'
            )

    if probabilities:
        output.append('<div style="margin-top:14px">')
        for name, probability in sorted(
            probabilities.items(), key=lambda item: item[1], reverse=True
        ):
            top = " top" if name == category else ""
            output.append(
                f'<div class="bar{top}"><div class="bn">{html.escape(name)}</div>'
                f'<div class="tr"><div class="fl2" '
                f'style="width:{probability * 100:.1f}%"></div></div>'
                f'<div class="bp">{probability * 100:.0f}%</div></div>'
            )
        output.append("</div>")

    priority = result["priority"]
    output.append(
        f'<div style="margin:15px 0 5px">'
        f'<span class="badge {priority.lower()}">{priority} priority</span>'
        f'<span class="sub" style="margin-left:8px">keyword rule, not the model</span>'
        f"</div>"
    )
    output.append(
        '<div class="fl" style="margin-top:17px">'
        "Suggested reply (fixed template, not model-generated)</div>"
    )
    output.append(f'<div class="reply">{html.escape(REPLIES[category])}</div>')
    output.append(
        f'<div class="kv">'
        f'<div><b>{result["ticket_tokens"]}</b><span>Ticket tokens</span></div>'
        f'<div><b>{result["model_tokens"]}</b><span>Model input tokens</span></div>'
        f'<div><b>{result["seconds"] * 1000:.0f} ms</b><span>Inference time</span></div>'
        f"</div>"
    )
    return "".join(output)


